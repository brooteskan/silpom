"""Train local relief visibility on native probes and an independent FP64 cell trace."""
import argparse
import ctypes
import hashlib
import json
import os
from pathlib import Path
os.environ.setdefault("OPENBLAS_NUM_THREADS", "2")
import numpy as np
from PIL import Image
from level_one import Evaluator, FP, UP, U, F, load_profiles


def pack(w):
    return np.ascontiguousarray(np.concatenate((w[0].T.ravel(), w[1], w[2], w[3])), np.float32)


class Native:
    def __init__(self, binary):
        self.dll = ctypes.CDLL(str((binary / "silpom_visibility.dll").resolve()))
        self.dll.EvaluateVisibility.argtypes = [FP,U,U,F,F,U,FP,U,FP,UP,U,U,U,F,ctypes.POINTER(F),FP,UP,FP]
        self.dll.EvaluateVisibility.restype = ctypes.c_bool

    def evaluate(self, p, q, ids, model=4, mode=2, confidence=.995, weights=None):
        q=np.ascontiguousarray(q,np.float32);ids=np.ascontiguousarray(ids,np.uint32)
        output=np.zeros((len(q),4),np.float32)
        stats=np.zeros((len(q),12),np.uint32);features=np.zeros((len(q),10),np.float32)
        packed=pack(weights) if weights is not None else None
        pointer=packed.ctypes.data_as(ctypes.POINTER(F)) if packed is not None else None
        ok=self.dll.EvaluateVisibility(p.height,*p.atlas,p.scale,p.reference,p.address,
            p.packed,len(p.packed),q,ids,len(q),model,mode,confidence,pointer,output,stats,features)
        if not ok: raise ValueError("Visibility evaluator rejected input")
        return output,stats,features


def requests(p,count,seed):
    rng=np.random.default_rng(seed)
    ids=rng.integers(len(p.packed),size=count,dtype=np.uint32)
    b=rng.random((count,2));b[b.sum(axis=1)>1]=1-b[b.sum(axis=1)>1]
    bary=np.column_stack((1-b.sum(axis=1),b))
    uv=np.einsum("ni,nij->nj",bary,p.uv[ids])
    incidence=rng.uniform(.03,1,count)
    incidence[:count//3]=rng.uniform(-.04,.18,count//3)
    angle=rng.uniform(-np.pi,np.pi,count)
    tangent=p.right[ids]*np.cos(angle)[:,None]+p.up[ids]*np.sin(angle)[:,None]
    light=p.normal[ids]*incidence[:,None]+tangent*np.sqrt(1-incidence**2)[:,None]
    reach=rng.choice([0,.025,.05,.1,.2,.3],count,p=[.2,.05,.1,.2,.3,.15])
    steps=rng.choice([5,9,18,32,64],count,p=[.05,.45,.15,.15,.2])
    return np.ascontiguousarray(np.column_stack((uv,light,reach,steps)),np.float32),ids


def predict(x,w):
    h=np.maximum(x@w[0]+w[1],0)
    z=np.clip(h*h@w[2]+w[3][0],-20,20)
    return 1/(1+np.exp(-z))


def fit(x,y,steps,seed):
    rng=np.random.default_rng(seed)
    w=[rng.normal(0,.25,(10,12)).astype(np.float32),np.full(12,.1,np.float32),
       rng.normal(0,.1,12).astype(np.float32),np.zeros(1,np.float32)]
    m=[np.zeros_like(v) for v in w];v=[np.zeros_like(a) for a in w]
    for step in range(1,steps+1):
        ids=rng.integers(len(x),size=1024);xx=x[ids]
        h=np.maximum(xx@w[0]+w[1],0);hs=h*h
        prob=1/(1+np.exp(-np.clip(hs@w[2]+w[3][0],-20,20)))
        error=(prob-y[ids])/len(ids)
        dh=error[:,None]*w[2]*2*h
        gradients=[xx.T@dh,dh.sum(axis=0),hs.T@error,np.asarray([error.sum()],np.float32)]
        rate=.003 if step<steps*.7 else .001
        for k,g in enumerate(gradients):
            m[k]=.9*m[k]+.1*g;v[k]=.999*v[k]+.001*g*g
            w[k]-=rate*m[k]/(1-.9**step)/(np.sqrt(v[k]/(1-.999**step))+1e-8)
    return w


def shader(models):
    lines=["// SPDX-License-Identifier: MIT","#pragma once",
           "// Generated by Tools/level_three.py. Four native probes; FP64 continuous-height labels.",
           "// Per model: 10 -> 12 squared-ReLU -> visibility logit (145 coefficients)."]
    for name,w in models.items():
        lines.append(f"static const float Visibility{name}W0[12][10] = {{")
        lines += ["    {"+", ".join(f"{float(v):.9e}f" for v in row)+"}," for row in w[0].T]
        lines.append("};")
        for suffix,array in (("B0",w[1]),("W1",w[2])):
            lines.append(f"static const float Visibility{name}{suffix}[12] = {{"+", ".join(f"{float(v):.9e}f" for v in array)+"};")
        lines.append(f"static const float Visibility{name}B1 = {float(w[3][0]):.9e}f;")
    return "\n".join(lines)+"\n"


def summary(output,stats):
    known=output[:,2]>=0;truth=output[:,2]==1
    base=output[:,0]==1;method=output[:,1]==1
    return dict(rays=len(output),reference_uncertain=int((~known).sum()),
        baseline_false_lit=int((known&base&~truth).sum()),baseline_false_shadow=int((known&~base&truth).sum()),
        method_false_lit=int((known&method&~truth).sum()),method_false_shadow=int((known&~method&truth).sum()),
        changed=int((base!=method).sum()),new_false_lit=int((known&method&~base&~truth).sum()),
        new_false_shadow=int((known&~method&base&truth).sum()),
        mean_baseline_quads=float(stats[:,8].mean()),mean_method_quads=float(stats[:,0].mean()),
        analytic=int(stats[:,1].sum()),probe_shadow=int(stats[:,2].sum()),
        neural_lit=int(stats[:,3].sum()),neural_shadow=int(stats[:,4].sum()),
        fallback=int(stats[:,5].sum()),gather_only=int(stats[:,6].sum()),inferences=int(stats[:,7].sum()))


def main():
    cli=argparse.ArgumentParser(description=__doc__)
    cli.add_argument("manifest",type=Path);cli.add_argument("binary_dir",type=Path);cli.add_argument("output",type=Path)
    cli.add_argument("--training-rays",type=int,default=300000)
    cli.add_argument("--rays",type=int,default=50000);cli.add_argument("--steps",type=int,default=6500)
    cli.add_argument("--reuse",action="store_true")
    a=cli.parse_args()
    if min(a.training_rays,a.rays,a.steps)<1:cli.error("Counts must be positive")
    if a.output.resolve().is_relative_to(Path(__file__).resolve().parents[1]/"Assets"):
        cli.error("Write experiment output outside shipping assets")
    a.output.mkdir(parents=True,exist_ok=True)
    native=Native(a.binary_dir);geometry=Evaluator(a.binary_dir)
    project=Path(__file__).resolve().parents[3]
    paths=["IrishFieldstoneTowerWelded/wall","IrishFieldstoneTowerOpenShaft/sculpted-stair-silpom",
           "IrishFieldstoneTowerOpenShaft/welded-doorway/trim-blocks","IrishFieldstoneTowerOpenShaft/welded-doorway/reveal"]
    report={"architecture":[10,12,1],"seed_policy":"disjoint train/calibration/held-out seeds", "profiles":{}}
    models={}
    for ident,name,p,_,_ in load_profiles(a.manifest,geometry):
        name=name.removeprefix("OpenShaft");model=ident+3
        path=project/"Assets/SilPOMPlanarAB"/paths[ident-1]/"height.png"
        p.height=np.ascontiguousarray(np.asarray(Image.open(path),np.float32)/65535);p.atlas=p.height.shape[::-1]
        folder=a.output/name;folder.mkdir(exist_ok=True)
        print(name,"generating reference data",flush=True)
        sets=[]
        for label,count,seed in [("train",a.training_rays,39913),("calibration",a.rays,65239),("test",a.rays,98239)]:
            file=folder/(label+".npz")
            if a.reuse and file.exists():
                cache=np.load(file);q,ids,o,s,x=[cache[k] for k in ("q","ids","o","s","x")]
            else:
                q,ids=requests(p,count,seed+ident)
                o,s,x=native.evaluate(p,q,ids,model)
                np.savez(file,q=q,ids=ids,o=o,s=s,x=x)
            sets.append((q,ids,o,s,x))
        q,ids,o,s,x=sets[0];valid=(s[:,10]>0)&(o[:,2]>=0)
        if valid.sum()<64:raise ValueError("Too few usable descriptors for "+name)
        print(name,"eligible",int(valid.sum()),"visible",float(o[valid,2].mean()),flush=True)
        weights_file=folder/"weights.npz"
        if a.reuse and weights_file.exists():
            cache=np.load(weights_file);w=[cache[f"arr_{i}"] for i in range(4)]
        else:
            w=fit(x[valid],o[valid,2],a.steps,7112031+ident);np.savez(weights_file,*w)
        models[name]=w
        entry={"height_sha256":hashlib.sha256(path.read_bytes()).hexdigest(),
               "training_rays":len(q),"training_descriptors":int(valid.sum()),"thresholds":{}}
        report["profiles"][name]=entry
        for label,confidence in [("default",.995),("conservative",.9999),("aggressive",.99)]:
            entry["thresholds"][label]={"confidence":confidence}
            for part,d in zip(("calibration","held_out"),sets[1:]):
                oo,ss,xx=native.evaluate(p,d[0],d[1],model,2,confidence,w)
                entry["thresholds"][label][part]=summary(oo,ss)
                if label=="default":
                    np.savez(folder/(part+"-evaluation.npz"),q=d[0],ids=d[1],o=oo,s=ss,x=xx)
                    parity=abs(predict(xx[ss[:,10]>0],w)-oo[ss[:,10]>0,3])
                    entry[part+"_numpy_native_max_probability_delta"]=float(parity.max(initial=0))
            print(name,label,entry["thresholds"][label]["held_out"],flush=True)
        (a.output/"training.json").write_text(json.dumps(report,indent=2)+"\n")
        (a.output/"NeuralVisibilityWeights.azsli").write_text(shader(models))


if __name__=="__main__":main()
