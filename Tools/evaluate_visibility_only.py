"""Calibrate and judge the existing Level 3 network without any runtime march."""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from PIL import Image
from level_one import Evaluator,load_profiles
from level_three import Native,summary


def classification(output,stats):
    if len(output)==0:return {"rays":0}
    result=summary(output,stats)
    known=output[:,2]>=0;truth=output[:,2]==1;pred=output[:,1]>=.5
    lit=int((known&truth).sum());shadow=int((known&~truth).sum())
    result.update(reference_lit=lit,reference_shadow=shadow,
        false_lit_rate=float((known&pred&~truth).sum()/max(shadow,1)),
        false_shadow_rate=float((known&~pred&truth).sum()/max(lit,1)),
        total_error_rate=float((known&(pred!=truth)).sum()/max(known.sum(),1)),
        descriptor_saturated=int(stats[:,11].sum()),max_height_quads=int(stats[:,0].max(initial=0)))
    return result


def threshold(output,stats):
    # Fit only disjoint calibration queries on which the MLP is evaluated.
    # Minimize total binary errors; ties favor fewer light leaks, then 0.5.
    valid=(stats[:,10]>0)&(output[:,2]>=0)
    p=output[valid,3];truth=output[valid,2]==1
    order=np.argsort(p);p=p[order];truth=truth[order]
    cuts=np.r_[0,np.flatnonzero(p[1:]!=p[:-1])+1,len(p)]
    positives=np.r_[0,np.cumsum(truth,dtype=np.int64)]
    negatives=np.arange(len(p)+1)-positives
    false_shadow=positives[cuts];false_lit=negatives[-1]-negatives[cuts]
    candidates=np.empty(len(cuts),np.float32)
    candidates[0]=np.nextafter(np.float32(0),np.float32(1))
    candidates[-1]=np.nextafter(np.float32(1),np.float32(0))
    middle=cuts[1:-1]
    candidates[1:-1]=p[middle-1]+(p[middle]-p[middle-1])*.5
    # Float32 midpoint rounding must not merge the two adjacent partitions.
    candidates[1:-1]=np.maximum(candidates[1:-1],np.nextafter(p[middle-1],np.float32(1)))
    eligible=(candidates>0)&(candidates<1)
    best=min(np.flatnonzero(eligible),key=lambda i:(int(false_shadow[i]+false_lit[i]),
        int(false_lit[i]),abs(float(candidates[i])-.5)))
    return float(candidates[best])


def main():
    cli=argparse.ArgumentParser(description=__doc__)
    cli.add_argument("manifest",type=Path);cli.add_argument("binary_dir",type=Path)
    cli.add_argument("trained_data",type=Path);cli.add_argument("output",type=Path)
    cli.add_argument("--relief-depth",type=float,default=.5)
    a=cli.parse_args()
    if not np.isfinite(a.relief_depth) or a.relief_depth<=0 or a.relief_depth>2:
        cli.error("Relief depth must be positive and at most 2")
    if a.output.resolve().is_relative_to(Path(__file__).resolve().parents[1]/"Assets"):
        cli.error("Write experiment datasets outside shipping assets")
    a.output.mkdir(parents=True,exist_ok=True)
    native=Native(a.binary_dir);geometry=Evaluator(a.binary_dir)
    project=Path(__file__).resolve().parents[3]
    paths=["IrishFieldstoneTowerWelded/wall","IrishFieldstoneTowerOpenShaft/sculpted-stair-silpom",
           "IrishFieldstoneTowerOpenShaft/welded-doorway/trim-blocks","IrishFieldstoneTowerOpenShaft/welded-doorway/reveal"]
    report={"architecture":[10,12,1],"relief_depth_multiplier":a.relief_depth,
            "weights":"original fixed Level 3 coefficients; only binary cutoffs recalibrated",
            "mode":"neural only; max 5 height quads including receiver; zero marcher calls",
            "threshold_selection":"minimum calibration binary errors, tie fewer false-lit, then nearest 0.5",
            "profiles":{}}
    lines=["// SPDX-License-Identifier: MIT","#pragma once",
           "// Generated by Tools/evaluate_visibility_only.py; calibration data only.",
           "// Binary visibility cutoffs, not area-light visible fractions."]
    for ident,name,p,_,_ in load_profiles(a.manifest,geometry):
        name=name.removeprefix("OpenShaft");model=ident+3
        path=project/"Assets/SilPOMPlanarAB"/paths[ident-1]/"height.png"
        p.height=np.ascontiguousarray(np.asarray(Image.open(path),np.float32)/65535);p.atlas=p.height.shape[::-1]
        p.scale*=a.relief_depth
        weights=np.load(a.trained_data/name/"weights.npz");weights=[weights[f"arr_{k}"] for k in range(4)]
        cache=np.load(a.trained_data/name/"calibration.npz")
        calibration=cache['q'].copy()
        calibration[:,5]=np.minimum(calibration[:,5],min(.3,8*abs(p.scale)))
        co,cs,_=native.evaluate(p,calibration,cache['ids'],model,3,.5,weights)
        cutoff=threshold(co,cs)
        entry={"classification_threshold":cutoff,"height_sha256":hashlib.sha256(path.read_bytes()).hexdigest()}
        report['profiles'][name]=entry
        lines.append(f"static const float Visibility{name}Threshold = {cutoff:.9e}f;")
        for part,label in (("calibration","calibration"),("test","held_out")):
            cache=np.load(a.trained_data/name/(part+".npz"));q,ids=cache['q'].copy(),cache['ids']
            q[:,5]=np.minimum(q[:,5],min(.3,8*abs(p.scale)))
            o,s,x=native.evaluate(p,q,ids,model,3,cutoff,weights)
            assert not s[:,5:7].any(),"Neural-only invoked a march"
            assert s[:,0].max()<=5,"Fixed input-acquisition budget exceeded"
            assert np.isin(o[:,1],[0,1]).all(),"Visibility must be binary"
            entry[label]=classification(o,s);entry[label]['by_samples']={}
            for count in (5,9,18,32,64):
                mask=q[:,6]==count
                entry[label]['by_samples'][str(count)]=classification(o[mask],s[mask])
            entry[label]['mlp_only']=classification(o[s[:,10]>0],s[s[:,10]>0])
            for domain,mask in (("unsaturated",s[:,11]==0),("saturated",s[:,11]>0)):
                entry[label][domain]=classification(o[mask],s[mask])
            ho,hs,_=native.evaluate(p,q,ids,model,2,.995,weights)
            entry[label]['historical_hybrid']=classification(ho,hs)
            np.savez(a.output/(name+"-"+label+".npz"),o=o,s=s,x=x,q=q,ids=ids)
        print(name,'threshold',cutoff,'held out',entry['held_out']['total_error_rate'],
              'false lit',entry['held_out']['method_false_lit'],'false shadow',entry['held_out']['method_false_shadow'],flush=True)
        (a.output/'evaluation.json').write_text(json.dumps(report,indent=2)+'\n')
    (a.output/'VisibilityClassificationThresholds.azsli').write_text('\n'.join(lines)+'\n')


if __name__=='__main__':main()
