"""Train a separate four-cap candidate with radius-independent angular edges.

Reuses fingerprinted continuous-cell labels, never refits shipping models.
The final test partition is read only after calibration checkpoint selection.
"""
import argparse,hashlib,json,math
from pathlib import Path
import numpy as np
import torch
from train_directional_estimators import partition
from frozen_bundle import source_fingerprint

MIN_WIDTH=math.radians(.1)
MAX_WIDTH=math.radians(8)

def parameters(raw):
    axes=torch.nn.functional.normalize(raw[:,:12].reshape(-1,4,3),dim=-1,eps=1e-6)
    cosine=torch.sigmoid(raw[:,12:28].reshape(-1,4,4)).sort(dim=-1,descending=True).values
    width=MIN_WIDTH+(MAX_WIDTH-MIN_WIDTH)*torch.sigmoid(raw[:,28:32])
    return axes,cosine,width

def logits(raw,directions):
    axes,c,width=parameters(raw)
    dot=torch.einsum('nd,bkd->bnk',directions,axes).clamp(-1,1)
    # First-order signed angular distance about each cap boundary. Its
    # derivative with respect to angle is one at the boundary. Unlike a fixed
    # cosine slope, width is in radians and independent of angular radius.
    inverse=torch.rsqrt((1-c*c).clamp(min=1e-6))
    margin=(dot[:,None]-c.transpose(1,2)[:,:,None,:])*inverse.transpose(1,2)[:,:,None,:]/width[:,None,None,:]
    return -margin.amax(dim=-1)

def query(raw,light,reach):
    axes,c,width=parameters(raw)
    dot=(axes*light[:,None,:]).sum(-1).clamp(-1,1)
    lo=torch.where(reach<=0,3,torch.where(reach<=.1,0,1));hi=torch.where(reach<=0,3,lo+1)
    blend=torch.where(reach<=0,0,((reach-torch.where(lo==0,.025,.1))/torch.where(lo==0,.075,.2)).clamp(0,1))
    row=torch.arange(len(raw),device=raw.device)
    threshold=c[row,:,lo]*(1-blend[:,None])+c[row,:,hi]*blend[:,None]
    margin=(dot-threshold)*torch.rsqrt((1-threshold*threshold).clamp(min=1e-6))/width
    return torch.where(light[:,2]<=0,0,torch.sigmoid(-margin.amax(-1)))

def header(model,path):
    text=['// SPDX-License-Identifier: MIT','#pragma once','// Generated by train_angular_edges.py. Independent angular-width four-cap candidate.']
    for name,value in (('W0',model[0].weight),('B0',model[0].bias),('W1',model[2].weight),('B1',model[2].bias)):
        a=value.detach().cpu().numpy().ravel();text.append(f'static const float SilPomAngularEdges{name}[{len(a)}] = {{')
        for i in range(0,len(a),8):text.append('    '+', '.join(f'{float(v):.9e}f' for v in a[i:i+8])+',')
        text.append('};')
    path.write_text('\n'.join(text)+'\n')

def main():
    cli=argparse.ArgumentParser(description=__doc__)
    for name in ('project','binary','labels','output'):cli.add_argument(name,type=Path)
    cli.add_argument('--steps',type=int,default=14000);args=cli.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    torch.set_num_threads(4);torch.manual_seed(81173)
    contract=json.loads((args.labels/'contract.json').read_text());wall=args.project/'Assets/SilPOMPlanarAB/IrishFieldstoneTowerWelded/wall'
    mesh=args.project/'Assets/SilPOMPlanarAB/IrishFieldstoneTowerOpenShaft/tower-open-shaft-no-landings-silpom.silpom.json'
    def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
    if contract['source']!=source_fingerprint(wall,mesh).hex() or contract['shared']!=sha(args.project/'Assets/SilPOMLearned/wall-shared.l4shared'):
        raise ValueError('Frozen material inputs changed')
    if contract['address']!=0 or contract['teacher']!=sha(args.binary/'silpom_appearance_reference.dll'):
        raise ValueError('Teacher contract changed; regenerate labels')
    datasets=[]
    for name in ('train','calibration'):
        d=np.load(args.labels/(name+'.npz'))
        if json.loads(str(d['contract']))!=contract:raise ValueError('Cached contract differs')
        split=partition(d['q'][:,:2]);assert np.all(split<8 if name=='train' else split==8)
        datasets.append(d)
    device='cuda' if torch.cuda.is_available() else 'cpu';print('Angular edges training on',device,flush=True)
    model=torch.nn.Sequential(torch.nn.Linear(20,32),torch.nn.ReLU(),torch.nn.Linear(32,32)).to(device)
    old=torch.load(args.labels/'head-4.pt',map_location='cpu',weights_only=True)
    with torch.no_grad():
        model[0].weight.copy_(old['0.weight']);model[0].bias.copy_(old['0.bias'])
        model[2].weight[:28].copy_(old['2.weight']);model[2].bias[:28].copy_(old['2.bias'])
        model[2].weight[28:].zero_();model[2].bias[28:].fill_(-2)
    tensors=[tuple(torch.from_numpy(d[k]).to(device) for k in ('x','y','directions')) for d in datasets]
    optimizer=torch.optim.Adam(model.parameters(),lr=.0008);best=None;score=float('inf');selected=0
    for step in range(args.steps):
        x,y,d=tensors[0];ids=torch.randint(len(x),(256,),device=device)
        z=logits(model(x[ids]),d);known=y[ids]>=0
        loss=torch.nn.functional.binary_cross_entropy_with_logits(z[known],y[ids][known])
        optimizer.zero_grad(set_to_none=True);loss.backward();torch.nn.utils.clip_grad_norm_(model.parameters(),10);optimizer.step()
        if step==args.steps//2:
            for group in optimizer.param_groups:group['lr']=.00025
        if step%100==0 or step==args.steps-1:
            with torch.no_grad():
                x,y,d=tensors[1];pred=torch.sigmoid(logits(model(x),d));current=(pred-y).abs()[y>=0].mean().item()
            if current<score:score=current;selected=step;best={k:v.detach().cpu().clone() for k,v in model.state_dict().items()}
        if step%1000==0:print(step,float(loss.detach()),score,flush=True)
    model.cpu();model.load_state_dict(best);torch.save(best,args.output/'head-angular-edges.pt')
    # Checkpoint is now frozen. Do not use final metrics to select a restart.
    test=np.load(args.labels/'test.npz');assert np.all(partition(test['q'][:,:2])==9)
    if json.loads(str(test['contract']))!=contract:raise ValueError('Final test contract changed')
    with torch.no_grad():
        raw=model(torch.from_numpy(test['x']));pred=torch.sigmoid(logits(raw,torch.from_numpy(test['directions']))).numpy()
        _,c,width=parameters(raw)
    target=test['y'];error=np.abs(pred-target);known=target>=0
    subsets={}
    for name,mask in (('one_texel_square',test['q'][:,9]==1),('filtered',test['q'][:,9]>1)):
        subsets[name]=dict(receivers=int(mask.sum()),mae=float(error[mask][known[mask]].mean()),
            median_edge_width_degrees=float(np.median(width.numpy()[mask])*180/np.pi))
    result=dict(experimental=True,calibration_mae=score,selected_step=selected,test_mae=float(error[known].mean()),
        arbitrary_angle_mae=float(error[:,:,32:][known[:,:,32:]].mean()),subsets=subsets,
        edge_width_radians=[MIN_WIDTH,MAX_WIDTH],label_contract=contract,
        training_steps=args.steps,source_sha256=sha(Path(__file__)),training_receivers=len(datasets[0]['x']),
        calibration_receivers=len(datasets[1]['x']),test_receivers=len(test['x']),test_used_after_checkpoint_freeze=True,
        reference='continuous FP64 cells; repeat; four reaches; receiver-footprint fraction, not uncertainty',
        formula='max_k((dot(L,A)-c)/sqrt(max(1-c*c,1e-6))/sigma); sigmoid(-max)',benchmark_performed=False)
    header(model,args.output/'AngularEdgeWeights.azsli')
    result['weights_sha256']=sha(args.output/'AngularEdgeWeights.azsli')
    (args.output/'quality.json').write_text(json.dumps(result,indent=2)+'\n')
    # Independent Torch receiver queries freeze interpolation and near-horizon
    # behavior for the NumPy parser and actual shipping GPU evaluator tests.
    old_fixture=json.loads((Path(__file__).resolve().parents[1]/'Tests/Reference/DirectionalEstimator.json').read_text())
    light=torch.tensor(old_fixture['light']);reach=torch.tensor(old_fixture['reach']);x=torch.from_numpy(test['x'][:len(light)])
    with torch.no_grad():expected=query(model(x),light,reach).numpy()
    fixture=dict(x=x.tolist(),light=light.tolist(),reach=reach.tolist(),expected=expected.tolist(),weights_sha256=result['weights_sha256'])
    (args.output/'fixture.json').write_text(json.dumps(fixture,indent=2)+'\n');print(result,flush=True)

if __name__=='__main__':main()
